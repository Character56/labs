counter = {
    "яблоки": 5,
    "бананы": 3,
    "апельсины": 10,
    "арбузы": 33
}

# Пункт 2: выводим, сколько чего за прилавком
for fruit, count in counter.items():
    print(f"За прилавком есть {count} {fruit}")

# Пункт 3: продали 2 яблока
counter["яблоки"] -= 2
print("\nПосле продажи 2 яблок:")
print(f"Яблок осталось: {counter['яблоки']}")

# Пункт 4: Ашот украл все арбузы
counter["арбузы"] = 0
print("\nАшот украл все арбузы!")

# Пункт 5: итоговый словарь
print("\nИтог:")
for fruit, count in counter.items():
    print(f"За прилавком осталось {count} {fruit}")